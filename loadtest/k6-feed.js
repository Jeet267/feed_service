/**
 * k6 load test: realistic mix of feed reads, trending reads and writes.
 *
 *   k6 run loadtest/k6-feed.js
 *   k6 run -e BASE_URL=http://localhost:3000 -e PEAK_VUS=200 loadtest/k6-feed.js
 *   docker compose --profile loadtest run --rm k6
 */
import http from 'k6/http';
import { check, sleep } from 'k6';

const BASE = __ENV.BASE_URL || 'http://localhost:3000';
const PEAK = Number(__ENV.PEAK_VUS || 100);

const AREAS = [
  { lat: 12.9352, lng: 77.6245 }, { lat: 12.9784, lng: 77.6408 },
  { lat: 12.9116, lng: 77.6474 }, { lat: 12.9698, lng: 77.75 },
  { lat: 12.925, lng: 77.5938 }, { lat: 13.0035, lng: 77.5647 },
  { lat: 12.8452, lng: 77.6602 }, { lat: 13.0358, lng: 77.597 },
];
const CATEGORIES = ['news', 'jobs', 'events', 'classifieds', 'alerts'];

export const options = {
  stages: [
    { duration: '30s', target: Math.round(PEAK / 2) },
    { duration: '1m', target: PEAK },
    { duration: '1m', target: PEAK },
    { duration: '20s', target: 0 },
  ],
  thresholds: {
    http_req_failed: ['rate<0.01'],
    'http_req_duration{endpoint:nearby}': ['p(95)<250'],
    'http_req_duration{endpoint:trending}': ['p(95)<100'],
    'http_req_duration{endpoint:create}': ['p(95)<300'],
  },
};

const pick = (arr) => arr[Math.floor(Math.random() * arr.length)];

function randomPoint() {
  const a = pick(AREAS);
  return { lat: a.lat + (Math.random() - 0.5) * 0.04, lng: a.lng + (Math.random() - 0.5) * 0.04 };
}

export default function () {
  const { lat, lng } = randomPoint();
  const headers = { 'Content-Type': 'application/json', 'x-user-id': `loadtest-${__VU}` };
  const r = Math.random();

  if (r < 0.6) {
    // 60%: nearby feed, sometimes scroll to page 2
    const url = `${BASE}/api/v1/feed/nearby?lat=${lat}&lng=${lng}&radiusKm=5&limit=20`;
    let res = http.get(url, { headers, tags: { endpoint: 'nearby' } });
    check(res, { 'nearby 200': (x) => x.status === 200 });
    const next = res.status === 200 ? res.json('nextCursor') : null;
    if (next && Math.random() < 0.3) {
      res = http.get(`${url}&cursor=${encodeURIComponent(next)}`, { headers, tags: { endpoint: 'nearby' } });
      check(res, { 'nearby page2 200': (x) => x.status === 200 });
    }
  } else if (r < 0.95) {
    // 35%: trending (served mostly from Redis)
    const res = http.get(`${BASE}/api/v1/feed/trending?lat=${lat}&lng=${lng}`, { headers, tags: { endpoint: 'trending' } });
    check(res, { 'trending 200': (x) => x.status === 200 });
  } else {
    // 5%: create a post
    const body = JSON.stringify({
      authorId: `loadtest-${__VU}`,
      title: 'Load test post',
      body: 'Generated by k6',
      category: pick(CATEGORIES),
      lat,
      lng,
    });
    const res = http.post(`${BASE}/api/v1/posts`, body, { headers, tags: { endpoint: 'create' } });
    check(res, { 'create 201': (x) => x.status === 201 });
  }

  sleep(Math.random() * 0.5 + 0.1);
}
